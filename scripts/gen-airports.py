#!/usr/bin/env python3
"""Compile an OurAirports airports.csv subset into src/.../flights/AirportData.java.

Keeps large airports plus medium airports with scheduled service, each with a code (IATA, else
ICAO ident). Records are "CODE lat lon size|City" joined by ';' (size 2 large, 1 medium; the city is
omitted with its '|' when empty), chunked for javac's 64 KiB constant limit. OurAirports is public
domain; the Virtual Radar Server standing-data is CC0 (docs/DATA-SOURCES.md).

City name: OurAirports gives the town the airport sits in (Ferno, Zaventem); standing-data gives the
place people name it for (Milan, Brussels) but has typos and region names. Both are cleaned the same
way, then `pick` chooses with no per-airport list: agree -> that; one empty -> the other; exactly one
appears in the airport's own name -> that one; else standing-data. Without the second argument the city
is OurAirports' alone.

Usage: scripts/gen-airports.py path/to/airports.csv [path/to/standing-data/airports]
(the second is the `airports/` folder of github.com/vradarserver/standing-data)
"""
import csv, glob, pathlib, re, sys, unicodedata

out = pathlib.Path(__file__).resolve().parent.parent / "src/me/jxl/kiosk/plugins/flights/AirportData.java"


def norm(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


def has(city, names):
    """Whole words only, so "Rome" is not found in "Jerome"."""
    return f" {norm(city)} " in f" {names} "


def clean(raw):
    """Drop a bracketed part (it can hold a comma), keep what is before a comma or slash, tidy noise."""
    s = re.sub(r"\s*\([^)]*\)?", "", raw).replace(";", ",").replace("|", "/")
    s = s.split(",")[0].split("/")[0].strip()
    s = re.sub(r"\s+(Airport|Lrrs)$", "", s)
    return re.sub(r"\bMc (?=[A-Z])", "Mc", s)


def strip_suffix(city, other, names):
    """Drop " City" or "[-Region] Island" only when the rest is what the other source says or what the
    airport's name uses, and the whole is not itself in the name (Atlantic City, Christmas Island)."""
    m = re.match(r"^(.*?)(?:-[^-]+)? Island$", city) or re.match(r"^(.*) City$", city)
    if not m or not m.group(1):
        return city
    rest = m.group(1)
    if norm(rest) == norm(other):
        return rest
    return city if has(city, names) or not has(rest, names) else rest


def pick(a, b, names):
    if not b:
        return a
    b = strip_suffix(b, a, names)
    if not a or norm(a) == norm(b):
        return b
    in_a, in_b = has(a, names), has(b, names)
    return a if in_a and not in_b else b


vrs = {}  # code -> (location, airport name)
if len(sys.argv) > 2:
    for f in glob.glob(sys.argv[2] + "/**/*.csv", recursive=True):
        for r in csv.DictReader(open(f, encoding="utf-8-sig", newline="")):
            if r["Location"].strip():
                v = (clean(r["Location"]), r["Name"])
                if r["IATA"]:
                    vrs[r["IATA"]] = v
                vrs[r["ICAO"]] = v

recs = []
for a in csv.DictReader(open(sys.argv[1], newline="", encoding="utf-8")):
    large = a["type"] == "large_airport"
    if not (large or (a["type"] == "medium_airport" and a["scheduled_service"] == "yes")):
        continue
    code = a["iata_code"] or a["icao_code"] or a["ident"]
    if not code or not code.isalnum():
        continue
    v = vrs.get(a["iata_code"]) or vrs.get(a["icao_code"] or a["ident"]) or ("", "")
    city = pick(clean(a["municipality"]), v[0], norm(a["name"] + " " + v[1]))
    recs.append(f'{code} {float(a["latitude_deg"]):.3f} {float(a["longitude_deg"]):.3f} {2 if large else 1}' + (f"|{city}" if city else ""))
recs.sort()
text = ";".join(recs)
# Non-ASCII (city names) as \u escapes so the build does not depend on javac's source encoding.
lit = lambda c: '"' + "".join(
    ch if ch.isascii() and ch not in '\\"' else
    "\\" + ch if ch in '\\"' else "\\u%04x" % ord(ch) for ch in c) + '"'
chunks = ",\n        ".join(lit(text[i:i + 12000]) for i in range(0, len(text), 12000))
out.write_text(
    "// Generated by scripts/gen-airports.py from OurAirports and VRS standing-data. Do not edit.\n"
    "package me.jxl.kiosk.plugins.flights;\n\nfinal class AirportData {\n"
    f"    private static final String[] DATA = {{\n        {chunks}\n    }};\n\n"
    "    static String records() {\n        return String.join(\"\", DATA);\n    }\n}\n")
print(f"{len(recs)} airports, {len(text)} B")
